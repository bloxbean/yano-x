package org.yanoproject.x.appchain.cli;

import org.yanoproject.x.appchain.formats.MemberCard;
import org.yanoproject.x.appchain.formats.Names;
import org.yanoproject.x.appchain.formats.SealedApp;
import org.yanoproject.x.devtools.AppChainSealResolver;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Writes {@code config/consensus.yaml} (exactly the sealed settings) and {@code config/node.yaml} (this node's
 * ports, storage, peers and Cardano view) for every application the node has joined.
 */
final class NodeConfig {
    private static final String HEADER = "# Generated by yano.sh appchain join; do not edit. Re-run join instead.\n";

    private NodeConfig() {
    }

    /** One joined application with this node's local view of it. */
    record Joined(SealedApp app, Map<String, String> peerOverrides, List<MemberCard> extraMembers,
                  List<String> removedMembers) {
    }

    static void write(NodeDir node, List<Joined> joined) {
        NodeDir.Identity identity = node.requireIdentity();
        Map<String, String> consensus = new TreeMap<>();
        Map<String, String> local = new TreeMap<>();
        String network = joined.getFirst().app().genesis().network();
        Map<String, Integer> indexes = node.chainIndexes(joined);
        for (Joined entry : joined) {
            SealedApp app = entry.app();
            app.genesis().settings().forEach(consensus::put);
            for (SealedApp.ChainGenesis chain : app.genesis().chains()) {
                String prefix = "yano.app-chain.chains[" + indexes.get(chain.id()) + "].";
                // Who leads anchoring is a local role (ADR-056 D10), so only the policy stays shared.
                chain.settings().forEach((key, value) -> {
                    if (!key.equals("anchor.enabled")) consensus.put(prefix + key, value);
                });
                local.put(prefix + "anchor.enabled", "false");
                chain.nodeSettings().forEach((key, value) -> {
                    if (!key.equals("peers") && !key.equals("signing-key")) local.put(prefix + key, value);
                });
                Anchoring.chainSettings(node, app.genesis().name(), chain.id())
                        .forEach((key, value) -> local.put(prefix + key, value));
                local.put(prefix + "signing-key", "${YANO_APPCHAIN_SIGNING_KEY}");
                local.put(prefix + "peers", String.join(",", peers(entry, identity.name())));
                if (chain.settings().keySet().stream().anyMatch(key -> key.startsWith("observers."))) {
                    local.put(prefix + "observation.l1-network-genesis-id", "devnet".equals(network)
                            ? "${YANO_APPCHAIN_L1_NETWORK_GENESIS_ID}"
                            : AppChainSealResolver.publicNetworkGenesisId(network));
                }
            }
        }
        boolean loopback = Names.host(identity.node()).equals("127.0.0.1")
                || Names.host(identity.node()).equals("localhost");
        local.put("quarkus.http.host", loopback ? "127.0.0.1" : "0.0.0.0");
        local.put("quarkus.http.port", Integer.toString(identity.httpPort()));
        local.put("yano.server.port", Integer.toString(identity.listenPort()));
        local.put("yano.storage.path", data(node, "chainstate"));
        local.put("yano.app-chain.storage.path", data(node, "appchain-chainstate"));
        local.put("yano.history.dir", data(node, "history"));
        // Rebuildable read indexes stay in this node's directory, beside its authoritative stores.
        local.put("yano.app-chain.indexer.storage.path", data(node, "appchain-indexers"));
        local.put("yano.plugins.bundle.\"org.yanoproject.x.eutxo.indexer\".storage-path",
                data(node, "appchain-indexers"));
        local.put("quarkus.log.file.path", node.path("logs", "yano.log").toString());
        local.put("yano.app-chain.api.keys", "${YANO_APPCHAIN_API_KEYS}");
        local.put("yano.app-chain.validation.strict", "true");
        local.put("yano.relay.connection.source-port-reuse", "false");
        local.put("yano.relay.connection.max-connections-per-ip", "500");
        if ("devnet".equals(network)) devnet(local, node, identity, joined.getFirst().app());
        // A public-network anchor leader needs current protocol parameters; the devnet carries its own.
        if (Anchoring.leadsAny(node) && !"devnet".equals(network)) {
            local.put("yano.epoch-params.tracking-enabled", "true");
        }
        NodeDir.write(node.path("config", "consensus.yaml"), AppChainSealResolver.yaml(consensus, HEADER));
        NodeDir.write(node.path("config", "node.yaml"), AppChainSealResolver.yaml(local, HEADER));
    }

    /** Every other member's node address, with local overrides, members added later, and removals. */
    static List<String> peers(Joined entry, String self) {
        Map<String, String> addresses = new LinkedHashMap<>();
        entry.app().peers().forEach((name, peer) -> addresses.put(name, peer.node()));
        entry.extraMembers().forEach(card -> addresses.put(card.name(), card.node()));
        entry.removedMembers().forEach(addresses::remove);
        addresses.putAll(entry.peerOverrides());
        addresses.remove(self);
        return new ArrayList<>(addresses.values());
    }

    /** The lead produces the Cardano devnet; everyone else follows it (ADR-056 D11). */
    private static void devnet(Map<String, String> local, NodeDir node, NodeDir.Identity identity, SealedApp app) {
        local.put("yano.genesis.shelley-genesis-file", node.path("runtime", "devnet-genesis.json").toString());
        local.put("yano.history.projection.enabled", "false");
        if (identity.name().equals(app.genesis().lead())) {
            local.put("yano.block-producer.genesis-timestamp", "${YANO_APPCHAIN_GENESIS_TIMESTAMP}");
        } else {
            String lead = app.peers().get(app.genesis().lead()).node();
            local.put("yano.block-producer.enabled", "false");
            local.put("yano.dev-mode", "false");
            local.put("yano.client.enabled", "true");
            local.put("yano.remote.host", Names.host(lead));
            local.put("yano.remote.port", Integer.toString(Names.port(lead)));
        }
    }

    private static String data(NodeDir node, String store) {
        return node.path("data", store).toString();
    }

    static boolean written(NodeDir node) {
        return Files.isRegularFile(node.path("config", "consensus.yaml"))
                && Files.isRegularFile(node.path("config", "node.yaml"));
    }

    static Path consensusFile(NodeDir node) {
        return node.path("config", "consensus.yaml");
    }

    /** The operator's own settings; never rewritten by the tool, loaded with the highest priority. */
    static Path localFile(NodeDir node) {
        return node.path("config", "local.yaml");
    }

    static void ensureLocalFile(NodeDir node) {
        if (java.nio.file.Files.exists(localFile(node))) return;
        NodeDir.write(localFile(node), """
                # This node's own settings, for example connector endpoints or JVM-independent tuning.
                # yano.sh appchain never rewrites this file, and settings here win over config/node.yaml.
                # Sealed consensus settings (config/consensus.yaml) cannot be changed here; start refuses.
                """);
    }

    /** {@code QUARKUS_CONFIG_LOCATIONS}: the first location wins, so local beats node beats sealed values. */
    static String locations(NodeDir node) {
        java.util.List<String> files = new java.util.ArrayList<>();
        if (java.nio.file.Files.isRegularFile(localFile(node))) files.add(localFile(node).toString());
        files.add(node.path("config", "node.yaml").toString());
        files.add(consensusFile(node).toString());
        return String.join(",", files);
    }

    /** Fails when the operator's local file sets a key the sealed consensus file sets. */
    static void requireLocalLeavesConsensusAlone(NodeDir node) {
        if (!java.nio.file.Files.isRegularFile(localFile(node))) return;
        java.util.Set<String> sealed = flatten(consensusFile(node)).keySet();
        // A %profile section applies to the same keys, so compare without the profile prefix.
        java.util.List<String> clashes = flatten(localFile(node)).keySet().stream()
                .map(key -> key.startsWith("%") && key.contains(".") ? key.substring(key.indexOf('.') + 1) : key)
                .filter(sealed::contains).sorted().toList();
        if (!clashes.isEmpty()) {
            throw CliException.failure("config/local.yaml changes sealed consensus settings: " + String.join(", ",
                    clashes) + ". Remove them; every member must run the sealed values");
        }
    }

    private static java.util.Map<String, String> flatten(Path file) {
        java.util.Map<String, String> values = new java.util.TreeMap<>();
        try {
            com.fasterxml.jackson.databind.JsonNode root = new com.fasterxml.jackson.databind.ObjectMapper(
                    new com.fasterxml.jackson.dataformat.yaml.YAMLFactory()).readTree(file.toFile());
            if (root != null) flatten("", root, values);
        } catch (java.io.IOException invalid) {
            throw CliException.failure(file + " is not valid YAML: " + invalid.getMessage());
        }
        return values;
    }

    private static void flatten(String prefix, com.fasterxml.jackson.databind.JsonNode node,
                                java.util.Map<String, String> values) {
        if (node.isObject()) {
            node.properties().forEach(entry -> flatten(prefix.isEmpty() ? entry.getKey()
                    : prefix + "." + entry.getKey(), entry.getValue(), values));
        } else if (node.isArray()) {
            for (int index = 0; index < node.size(); index++) flatten(prefix + "[" + index + "]", node.get(index), values);
        } else {
            values.put(prefix, node.asText());
        }
    }
}
